struct ReturnObject3 {
    struct promise_type {
        int val_;
        std::suspend_always yield_value(int val) {
            this->val_ = val;
            return std::suspend_always{};
        }

        ReturnObject3 get_return_object() {
            return { std::coroutine_handle<promise_type>::from_promise(*this)};
        }
        std::suspend_never initial_suspend() { return {}; }
        std::suspend_always final_suspend() noexcept { return {}; }
        void unhandled_exception() {}
    };

    // You can resume(), destroy(), check if it’s done(), or access its promise() object.
    std::coroutine_handle<promise_type> handle;
    ReturnObject3(std::coroutine_handle<promise_type> h) : handle{h} { }
    operator std::coroutine_handle<promise_type>() const { return handle; }

    // Helper function to get the val_ memver within promise object
    int get_value() const { return handle.promise().val_; }
};
// co_yield 5; will call promise_type::yield_value(5);
// This value could be saved in promise object and retrive it
// frome coroutine_handle

ReturnObject3 generator(int start, int end, int steps = 1) {
    for (int val{start}; val<end; val += steps) {
        // When a coroutine uses co_yield X;, the compiler translates it into a call to promise_type::yield_value(X).
        co_yield val;
    }
}


struct ReturnObject2 {
    struct promise_type {
        // promise_type() = default; /* Implicitly generated by compiler */

        std::suspend_never initial_suspend() { return {}; }
        std::suspend_never final_suspend() noexcept { return {}; }

        ReturnObject2 get_return_object() {
            return ReturnObject2{
                // Return a ReturnObject2 that wraps a coroutine handle pointing to this promise.
                std::coroutine_handle<promise_type>::from_promise(*this)
            };
            /* std::coroutine_handle<promise_type> is a tiny object that stores a pointer to the coroutine frame.
            from_promise(*this) means:
                Take the current promise object (*this).
                Look up which coroutine frame it belongs to.
                Build a coroutine_handle that can later resume, destroy, or check status of this coroutine.*/
        }
        void unhandled_exception() {}
    };
    // ReturnObject2() = default; /* Implicitly generated by compiler */


/*  std::coroutine_handle<> is a type-erased coroutine handle.
It can point to a coroutine of any promise_type.
Think of it as void* for coroutine frames.
ReturnObject2 just stores this handle.
The constructor takes the handle from get_return_object() and saves it:
So now ReturnObject2 is the “controller” object for the coroutine.*/
    std::coroutine_handle<> handle;
    ReturnObject2(std::coroutine_handle<> handle_) : handle{handle_} {}
};
/*  How they connect together
1. Coroutine call starts (foo2())
    Compiler makes a coroutine frame with a promise_type inside.
    Calls promise.get_return_object().

2. get_return_object() runs
    Calls std::coroutine_handle<promise_type>::from_promise(*this).
    Creates a handle to the coroutine frame.
    Wraps it in a ReturnObject2.

3. ReturnObject2 constructed
    Its constructor takes the handle and stores it in handle.
    Now the caller has a handle to control the coroutine.

So in short:
    from_promise(*this) → “Get a handle to the coroutine frame that owns this promise.”
    ReturnObject2(std::coroutine_handle<> handle_) → “Store that handle so the caller can resume/destroy the coroutine.”*/

